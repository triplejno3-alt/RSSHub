async function i(n) {
    let { region: i, keyword: a } = n.req.param();
    if (!Object.keys(r).includes(i)) throw Error(`Unsupported region code: ${i}`);
    let o = r[i].baseUrl,
        s = await e.raw(o),
        c = s.headers
            .getSetCookie()
            ?.map((e) => e.split(`;`)[0])
            .join(`; `),
        l = s._data.match(/"csrfToken":"(.*?)","/)[1],
        u = (await e(r[i].api, { method: `POST`, headers: { cookie: c, 'csrf-token': l, referer: r[i].referer(a) }, body: { ...r[i].payload, query: a } })).data.results
            .filter((e) => e.listingCard)
            .map(({ listingCard: e }) => ({
                title: e.title,
                description: `${e.photoUrls.map((e) => `<img src="${e.replace(`_thumbnail.`, `_progressive.`)}">`).join(``)}<br>${Object.values(e.belowFold)
                    .map((e) => e.stringContent.replaceAll(`\r`, `<br>`))
                    .join(`<br>`)}`,
                author: `${e.seller.firstName ?? ``} ${e.seller.lastName ?? ``} (@${e.seller.username})`.trim(),
                pubDate: t(e.overlayContent.timestampContent.seconds.low, `X`),
                guid: `${i}:${e.id}`,
                link: `${o}/p/${e.id}/`,
            }));
    return { title: `Carousell ${i.toUpperCase()} Search - ${a}`, item: u };
}
